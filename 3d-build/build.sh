#!/bin/sh
# Rebuilds the 3D data used by the site (data/body3d.js and data/spine3d.js).
# Needs Python 3 with: numpy scipy scikit-image trimesh rtree fast-simplification
#   pip install numpy scipy scikit-image trimesh rtree fast-simplification
# Inputs in this folder: MakeHuman CC0 base mesh (base.obj), targets (t/), rig weights (weights.mhw), skeleton (default.mhskel).
set -e
cd "$(dirname "$0")"
python3 body5.py        # male + female bodies, region maps, landmarks  -> bodydata.js, lm.npy
python3 spine.py        # lumbar vertebrae, sacrum, pelvis, leg bones       -> spine_parts.npy
python3 spine2.py       # neck and chest vertebrae, discs, ribs, arm bones   -> spine_parts2.npy
python3 spine_place2.py # places bones, cord and nerves in the body       -> spinedata.js
python3 rig.py          # skeleton + skin weights for test poses           -> rigdata.js
{ echo '/* Realistic male and female bodies built from the MakeHuman base mesh and targets (CC0, makehumancommunity.org). Generated by 3d-build/body5.py */'; cat bodydata.js; } > ../data/body3d.js
{ echo '/* Full spine C1–coccyx, ribs, sternum, shoulder girdle, pelvis, arm and leg bones, spinal cord and nerves. Generated by 3d-build/spine2.py and spine_place2.py */'; cat spinedata.js; } > ../data/spine3d.js
{ echo '/* Bone weights and joint positions for posing the 3D bodies in the bedside-test pictures (from MakeHuman CC0 rig). Generated by 3d-build/rig.py */'; cat rigdata.js; } > ../data/rig3d.js
echo "3D data rebuilt."
